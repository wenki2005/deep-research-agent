"""Render a ResearchReport (and research notes) as readable Markdown."""

from __future__ import annotations

from .models import ResearchNotes, ResearchReport
from .provenance import ProvenanceRegistry


def literal_text(text: str) -> str:
    """Render external quotes/titles as literal text, not injected links or HTML."""
    import html
    import re

    value = html.escape(text, quote=False)
    value = re.sub(r"https?://[^\s<>]+", "[原文中的链接已隐藏]", value)
    for char in ("\\", "`", "*", "_", "[", "]", "#"):
        value = value.replace(char, "\\" + char)
    return value.replace("\n", " ")


def notes_to_context(
    question: str, notes: list[ResearchNotes], provenance: ProvenanceRegistry | None = None
) -> str:
    """Build the prompt context handed to the Writer agent."""
    blocks: list[str] = [f"# Research question\n{question}\n"]
    if provenance is not None:
        blocks.append(
            "## 可引用证据包（强制）\n"
            "只能引用下列来源编号。source_urls 字段请填写 SRC-001 这类编号；"
            "不要填写记忆中的网址或自行猜测网址。evidence_quote 必须逐字复制摘录。\n"
            + provenance.citation_packet()
        )
    for i, note in enumerate(notes, 1):
        blocks.append(f"## Researcher {i} — query: {note.query}")
        if not note.findings:
            blocks.append("(no findings)")
        for finding in note.findings:
            blocks.append(
                f"- [{finding.status}/{finding.confidence}] {finding.content}\n"
                f"  Evidence: {finding.evidence_quote}\n"
                f"  Supporting URLs: {', '.join(finding.source_urls)}"
            )
        if note.sources:
            blocks.append("Sources:")
            for source in note.sources:
                blocks.append(
                    f"  - {source.title} — {source.url} ({source.source_type}, {source.published_at or 'date unknown'})"
                )
    return "\n\n".join(blocks)


def report_to_markdown(report: ResearchReport, question: str = "") -> str:
    """Serialize a ResearchReport into a self-contained Markdown document."""
    lines: list[str] = [f"# {literal_text(report.title)}", ""]
    question = question or report.question
    if question:
        lines += ["**研究问题 / Research question:**", f"> {literal_text(question)}", ""]
    lines += ["## 摘要 / Summary", "", report.summary, ""]
    lines += ["## 核心发现 / Key findings", ""]
    for finding in report.key_findings:
        lines += [
            f"### {finding.topic} [{finding.status}/{finding.confidence}]",
            "",
            finding.details,
        ]
        if finding.evidence:
            lines += ["", "**证据 / Evidence:**"]
            for evidence in finding.evidence:
                lines.append(
                    f"- [{evidence.status}/{evidence.support_level}] {literal_text(evidence.evidence_quote or evidence.content)}"
                )
                for url in evidence.source_urls:
                    lines.append(f"  - Source: <{url}>")
        lines.append("")
    lines += ["## 参考来源 / Sources", ""]
    if report.sources:
        for source in report.sources:
            lines.append(f"- **{literal_text(source.title)}** — <{source.url}>")
    else:
        lines.append("(无 / none)")
    lines += [""]
    if report.limitations:
        lines += ["## 局限 / Limitations", "", report.limitations, ""]
    if report.recommendations:
        lines += ["## 建议 / Recommendations", "", report.recommendations, ""]
    lines += ["## 核验状态 / Verification", "", f"引文匹配覆盖率（非事实准确率）: {report.evidence_coverage:.0%}", report.verification_summary, ""]
    lines += [
        "---",
        "",
        "*Generated by Deep Research Agent — a multi-agent research pipeline built on the OpenAI Agents SDK.*",
        "",
    ]
    return "\n".join(lines)
